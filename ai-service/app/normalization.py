def normalize_skill(skill_name: str) -> str:
    """Normalize a skill name using the alias taxonomy."""
    if not skill_name:
        return ""
    key = skill_name.strip().lower()
    return SKILL_ALIASES.get(key, skill_name.strip())

def get_category_for_skill(normalized_name: str) -> str:
    """Get category for normalized skill name."""
    return SKILL_CATEGORIES.get(normalized_name, "Other")
